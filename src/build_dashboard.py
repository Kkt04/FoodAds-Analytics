"""Build a single self-contained HTML dashboard (outputs/dashboard.html) from the tables and charts."""
from __future__ import annotations

import argparse
import base64
import html
import json

import pandas as pd

from src import config

CHARTS = [
    ("01_monthly_trend", "Monthly ad revenue and ROAS"),
    ("02_category_roas", "ROAS by category"),
    ("06_segment_heatmap", "ROAS by category x city tier"),
    ("03_placement_roas_fill", "Placements: ROAS vs fill rate"),
    ("04_fill_rate_trend", "Fill rate trend"),
    ("05_retention_heatmap", "Advertiser retention cohorts"),
    ("07_ab_test_ctr", "A/B test: CTR"),
]

CSS = """
:root{--bg:#faf7f2;--card:#fff;--text:#222;--muted:#666;--accent:#FC8019;--line:#e8e2d8;--bad:#D64545;--good:#2E9E6B}
@media (prefers-color-scheme:dark){:root{--bg:#161616;--card:#222;--text:#eee;--muted:#aaa;--line:#333}}
*{box-sizing:border-box}body{margin:0;font-family:system-ui,-apple-system,Segoe UI,Roboto,sans-serif;background:var(--bg);color:var(--text)}
header{padding:24px 28px;border-bottom:3px solid var(--accent)}h1{margin:0;font-size:22px}
.sub{color:var(--muted);font-size:13px;margin-top:4px}
.banner{background:#FFF3CD;color:#664d03;padding:8px 28px;font-size:13px}
main{padding:24px 28px;max-width:1200px;margin:auto}
.kpis{display:grid;grid-template-columns:repeat(auto-fit,minmax(150px,1fr));gap:12px;margin-bottom:24px}
.kpi{background:var(--card);border:1px solid var(--line);border-radius:10px;padding:14px}
.kpi .v{font-size:22px;font-weight:700}.kpi .l{font-size:12px;color:var(--muted);margin-top:2px}
.grid{display:grid;grid-template-columns:repeat(auto-fit,minmax(420px,1fr));gap:16px}
.card{background:var(--card);border:1px solid var(--line);border-radius:10px;padding:14px;overflow-x:auto}
.card h2{font-size:14px;margin:0 0 8px}.card img{max-width:100%;height:auto;background:#fff;border-radius:6px}
table{border-collapse:collapse;width:100%;font-size:13px}th,td{padding:6px 8px;border-bottom:1px solid var(--line);text-align:left}
.FIX{color:var(--bad);font-weight:700}.GROW{color:var(--good);font-weight:700}
h3{margin:28px 0 10px}footer{color:var(--muted);font-size:12px;padding:24px 28px}
"""


def _img(name: str) -> str:
    data = (config.CHART_DIR / f"{name}.png").read_bytes()
    return "data:image/png;base64," + base64.b64encode(data).decode()


def _kpi(value: str, label: str) -> str:
    return f'<div class="kpi"><div class="v">{html.escape(value)}</div><div class="l">{html.escape(label)}</div></div>'


def run(verbose: bool = True) -> str:
    k = pd.read_csv(config.TABLE_DIR / "01_overall_kpis.csv").iloc[0]
    ab = json.loads((config.REPORT_DIR / "ab_test_result.json").read_text())
    seg = pd.read_csv(config.TABLE_DIR / "09_segments_to_grow_or_fix.csv")
    opp = pd.read_csv(config.TABLE_DIR / "opportunity_sizing.csv")
    base_opp = opp[opp.scenario == "Base"]["incremental_revenue_3m"].sum() / 1e7

    kpis = "".join([
        _kpi(f"INR {k.ad_revenue_inr / 1e7:.1f} cr", "Ad revenue (advertiser spend)"),
        _kpi(f"{k.impressions / 1e6:,.0f} M", "Impressions"),
        _kpi(f"{k.ctr_pct:.2f}%", "CTR"),
        _kpi(f"INR {k.cpm_inr:.0f}", "CPM"),
        _kpi(f"{k.roas:.2f}x", "ROAS"),
        _kpi(f"{int(k.advertisers_with_spend)}", "Advertisers with spend"),
        _kpi(f"{ab['verdict']}", f"A/B verdict (CTR {ab['ctr_rel_lift'] * 100:+.0f}%)"),
        _kpi(f"+INR {base_opp:.2f} cr", "Inventory opportunity / quarter (base)"),
    ])

    cards = "".join(f'<div class="card"><h2>{t}</h2><img alt="{t}" src="{_img(n)}"></div>' for n, t in CHARTS)

    focus = seg[seg.action.isin(["FIX", "GROW"])].copy()
    focus = pd.concat([focus[focus.action == "FIX"].head(6), focus[focus.action == "GROW"].tail(6)])
    rows = "".join(
        f"<tr><td>{html.escape(r.category)}</td><td>{html.escape(r.city_tier)}</td><td>{r.roas:.2f}x</td>"
        f"<td>{r.roas_vs_overall:.2f}</td><td class='{r.action}'>{r.action}</td></tr>"
        for r in focus.itertuples())
    table = ("<table><tr><th>Category</th><th>City tier</th><th>ROAS</th><th>vs overall</th><th>Action</th></tr>"
             + rows + "</table>")

    page = f"""<!DOCTYPE html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>FoodAds Analytics Dashboard</title><style>{CSS}</style></head><body>
<header><h1>FoodAds Analytics: Ads P&amp;L Dashboard</h1>
<div class="sub">Jul 2025 - Jun 2026 | simulated food-delivery ads marketplace</div></header>
<div class="banner">All data in this dashboard is <b>simulated</b>. It is not real data from any company.</div>
<main>
<div class="kpis">{kpis}</div>
<div class="grid">{cards}</div>
<h3>Segments to fix and grow (category x city tier)</h3>
<div class="card">{table}</div>
</main>
<footer>Generated by the FoodAds Analytics pipeline. See README.md for metric definitions and method.</footer>
</body></html>"""
    out = config.OUT_DIR / "dashboard.html"
    out.write_text(page, encoding="utf-8")
    if verbose:
        print(f"  dashboard: {out}")
    return str(out)


def main() -> None:
    argparse.ArgumentParser(description="Build HTML dashboard").parse_args()
    run()


if __name__ == "__main__":
    main()
